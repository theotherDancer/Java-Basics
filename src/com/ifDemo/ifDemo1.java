package com.ifDemo;

public class ifDemo1 {
    static void main(String[] args) {
        //下面学习if语句
        int a=10;
        if(a>0){
            System.out.println("a是正数");
        }else if(a<0){
            System.out.println("a是负数");
        }else{
            System.out.println("a是零");
        }
    }
}
