package com.operator;

public class OperatorDemo1
{
    static void main(String[] args) {
        //这个小节主要学习算术运算符号
        //包括+，-，*，/，%
        //首先演示整数运算
        int a = 10;
        int b = 3;
        System.out.println("a+b="+(a+b));
        System.out.println("a-b="+(a-b));
        System.out.println("a*b="+(a*b));
        System.out.println("a/b="+(a/b));
        System.out.println("a%b="+(a%b));
        System.out.println("-----------------");
        double c = 10.0;
        double d = 3.0;
        System.out.println("c+d="+(c+d));
        System.out.println("c-d="+(c-d));
        System.out.println("c*d="+(c*d));
        System.out.println("c/d="+(c/d));
        System.out.println("c%d="+(c%d));
    }
}
